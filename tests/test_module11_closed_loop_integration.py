@pytest.mark.anyio
async def test_full_closed_loop_result_day_recovery():
    """Execute complete closed-loop lifecycle from result-day traffic through actuation to recovery."""
    # -----------------------------------------------------------------------
    # STAGE 1: Start the IEMCRP simulation & verify health
    # -----------------------------------------------------------------------
    adapter = get_portal_adapter("college_portal")
    health = adapter.health_check()
    assert health["status"] == "HEALTHY", "IEMCRP portal health check failed"
    assert "db_pool" in health

    # -----------------------------------------------------------------------
    # STAGE 2: Start controlled result-day traffic using existing personas
    # -----------------------------------------------------------------------
    start_res = await TRAFFIC_CONTROLLER.start(
        scenario="CONTINUOUS_RESULT_DAY",
        start_phase=TrafficPhase.RESULT_RUSH,
        loop_continuously=False,
    )
    assert start_res["status"] in ("STARTED", "ALREADY_RUNNING")
    assert TRAFFIC_CONTROLLER.is_running is True

    # Allow authentic personas to generate real HTTP requests against IEMCRP
    await asyncio.sleep(0.8)

    # -----------------------------------------------------------------------
    # STAGE 3: Confirm telemetry is being generated continuously
    # -----------------------------------------------------------------------
    transactions = TRAFFIC_CONTROLLER.get_recent_transactions(limit=20)
    assert len(transactions) > 0, "No transactions generated by personas"
    live_tel = adapter.get_telemetry()
    assert live_tel.portal_id in ("college_portal", "iemcrp")
    assert live_tel.timestamp is not None
    assert live_tel.cpu_percent >= 0.0

    # -----------------------------------------------------------------------
    # STAGE 4: Enter elevated-load / saturation condition
    # -----------------------------------------------------------------------
    TRAFFIC_CONTROLLER.set_scenario(phase=TrafficPhase.SATURATION, target_vus=12500)
    # Simulate DB pool contention under stampede
    for _ in range(42):
        DB_POOL.acquire_connection(timeout_sec=0.01)

    sat_tel = adapter.get_telemetry()
    assert sat_tel.db_connections >= 70.0, "DB pool utilization did not rise under saturation"

    # -----------------------------------------------------------------------
    # STAGE 5: Run the REAL serialized production models
    # -----------------------------------------------------------------------
    assert FORECASTER.is_ready is True and FORECASTER.model is not None, "M2 forecaster is not real model"
    assert DETECTOR.is_ready is True and DETECTOR.model is not None, "M3 detector is not real model"
    assert RCA_CLASSIFIER.is_ready is True and RCA_CLASSIFIER.model is not None, "M4 classifier is not real model"
    assert ACTION_ENGINE.is_ready is True and ACTION_ENGINE.model is not None, "M5 action policy is not real model"

    # Run complete control cycle with autonomous remediation enabled
    cycle = EXPLAINABLE_PIPELINE.run_cycle(
        portal_id="college_portal",
        auto_approve=True,
        force_bypass_cooldown=True,
    )
    assert isinstance(cycle, ControlCycle)

    # -----------------------------------------------------------------------
    # STAGE 6: Verify control loop outputs across all required model stages
    # -----------------------------------------------------------------------
    # 1. Forecast (M2 XGBoost)
    assert "safe_capacity" in cycle.forecast
    assert "capacity_pressure_index" in cycle.forecast
    assert "5m_forecast" in cycle.forecast
    assert cycle.models["M2"].provenance == "LIVE_MODEL"
    assert cycle.models["M2"].status == "COMPLETE"

    # 2. Anomaly score/state (M3 Isolation Forest)
    assert "anomaly_score" in cycle.anomaly
    assert "is_anomaly" in cycle.anomaly
    assert "severity" in cycle.anomaly
    assert cycle.models["M3"].provenance == "LIVE_MODEL"
    assert cycle.models["M3"].status == "COMPLETE"

    # 3. RCA class and probabilities (M4 XGBoost)
    assert "rca_class" in cycle.rca
    assert "probabilities" in cycle.rca
    assert len(cycle.rca["probabilities"]) >= 8
    assert cycle.rca["confidence"] > 0.0
    assert cycle.models["M4"].provenance == "LIVE_MODEL"
    assert cycle.models["M4"].status == "COMPLETE"

    # 4. Causal path (M4 NetworkX Causal Graph)
    assert isinstance(cycle.causal_path, list)
    assert len(cycle.causal_path) >= 2
    # Verify NetworkX DAG active path structure
    dag_path = RESULT_DAY_CAUSAL_DAG.get_active_causal_path()
    assert "DB_POOL" in dag_path or "postgresql_db" in cycle.causal_path

    # 5. Action recommendation & confidence (M5 PyTorch Policy)
    assert "selected_action" in cycle.action_recommendation
    assert "all_action_probabilities" in cycle.action_recommendation
    assert len(cycle.action_recommendation["all_action_probabilities"]) == 11
    assert cycle.action_recommendation["confidence"] > 0.0
    assert cycle.models["M5"].provenance == "LIVE_MODEL"
    assert cycle.models["M5"].status == "COMPLETE"

    # 6. Safety validation (M6 Deterministic Guardrail)
    assert cycle.safety_decision in ("APPROVED", "HITL_REQUIRED")
    assert "is_safe" in cycle.safety_validation
    assert cycle.models["M6"].provenance == "LIVE_MODEL"
    assert cycle.models["M6"].status == "COMPLETE"

    # 7. Actuation record (M7 Physical Actuator)
    assert cycle.actuation_status == "EXECUTED"
    assert cycle.actuation is not None
    assert cycle.actuation["status"] in ("SUCCESS", "EXECUTED")
    assert cycle.models["M7"].provenance == "LIVE_MODEL"
    assert cycle.models["M7"].status == "COMPLETE"

    # -----------------------------------------------------------------------
    # STAGE 7: Verify actuator changes simulated system state
    # -----------------------------------------------------------------------
    assert len(cycle.stabilization_trajectory) == 5
    assert cycle.stabilization_trajectory[0]["state"] == "PRE-ACTION"
    assert cycle.stabilization_trajectory[-1]["state"] == "NOMINAL"
    assert len(cycle.metric_deltas) >= 6

    # -----------------------------------------------------------------------
    # STAGE 8: Collect post-actuation telemetry
    # -----------------------------------------------------------------------
    assert cycle.post_metrics is not None
    post_metrics = cycle.post_metrics
    pre_metrics = cycle.pre_metrics
    assert "p95_ms" in post_metrics
    assert "db_connections" in post_metrics
    assert "errors" in post_metrics

    # -----------------------------------------------------------------------
    # STAGE 9: Next control cycle observes changed telemetry
    # -----------------------------------------------------------------------
    # Relieve artificial pool pressure
    while DB_POOL.active_connections > 0:
        DB_POOL.release_connection()

    next_cycle = EXPLAINABLE_PIPELINE.run_cycle(
        portal_id="college_portal",
        auto_approve=True,
        force_bypass_cooldown=True,
    )
    assert next_cycle.cycle_id != cycle.cycle_id
    assert next_cycle.pre_metrics is not None

    # -----------------------------------------------------------------------
    # STAGE 10: Verify directional improvement where appropriate
    # -----------------------------------------------------------------------
    # Latency moved toward recovery
    assert post_metrics["p95_ms"] <= pre_metrics["p95_ms"]
    # Error rate moved toward recovery
    assert post_metrics["errors"] <= pre_metrics["errors"]
    # DB connections moved toward relief in metric deltas
    deltas = {d["metric_name"]: d for d in cycle.metric_deltas}
    assert "db_connections" in deltas
    assert deltas["db_connections"]["after"] <= deltas["db_connections"]["before"]

    # -----------------------------------------------------------------------
    # STAGE 11: Verify stabilization/recovery reaches NOMINAL
    # -----------------------------------------------------------------------
    TRAFFIC_CONTROLLER.set_scenario(phase=TrafficPhase.NORMAL, target_vus=50)
    await asyncio.sleep(0.3)
    recovery_cycle = EXPLAINABLE_PIPELINE.run_cycle(
        portal_id="college_portal",
        auto_approve=True,
        force_bypass_cooldown=True,
    )
    assert recovery_cycle.recovery_state in ("NOMINAL", "STABILIZING")


@pytest.mark.anyio
async def test_control_loop_survives_model_inference_exception(caplog):
    """Verify control loop daemon survives model inference failures with deterministic fallback."""
    loop_engine = ContinuousControlLoop(interval_seconds=0.05)
    await loop_engine.start()
    assert loop_engine.running is True

    try:
        # 1. Temporarily force M3 Isolation Forest model exception
        with caplog.at_level(logging.ERROR):
            with patch.object(DETECTOR, "detect", side_effect=RuntimeError("Simulated M3 Isolation Forest failure")):
                degraded_cycle = loop_engine.step("college_portal")

                # Verify daemon did NOT die
                assert loop_engine.running is True

                # Verify cycle was marked failed / degraded
                assert degraded_cycle.models["M3"].status == "FAILED"
                assert degraded_cycle.recovery_state == "DEGRADED"

                # Verify deterministic safety behavior remains available
                assert degraded_cycle.safety_decision in ("NO_ACTION_REQUIRED", "APPROVED", "HITL_REQUIRED")
                assert degraded_cycle.safety_validation is not None

                # Verify exception was logged
                assert any("M3 Detector inference error" in r.message for r in caplog.records)

        # 2. Verify next cycle executes normally when model recovers
        normal_cycle = loop_engine.step("college_portal")
        assert loop_engine.running is True
        assert normal_cycle.models["M3"].status == "COMPLETE"
        assert normal_cycle.models["M3"].output_summary.get("status") != "FAILED"

    finally:
        await loop_engine.stop()
        assert loop_engine.running is False


